import Foundation

/// One entry in the clipboard history.
public struct ClipItem: Codable, Identifiable, Equatable, Sendable {
    public enum Kind: String, Codable, Sendable {
        case text, image
    }

    public var id: UUID
    public var date: Date
    public var kind: Kind
    public var text: String?
    /// File name inside the clips folder.
    public var imageFile: String?
    public var appName: String?

    public init(id: UUID = UUID(), date: Date = Date(), kind: Kind, text: String? = nil,
                imageFile: String? = nil, appName: String? = nil) {
        self.id = id
        self.date = date
        self.kind = kind
        self.text = text
        self.imageFile = imageFile
        self.appName = appName
    }
}

public enum History {
    /// Newest first. Copying the same text again moves it to the top instead
    /// of adding a second row. Returns what fell out, so its files can go too.
    public static func inserting(_ item: ClipItem, into list: [ClipItem],
                                 limit: Int) -> (list: [ClipItem], dropped: [ClipItem]) {
        var dropped: [ClipItem] = []
        var rest = list
        if item.kind == .text, let text = item.text {
            let key = text.trimmingCharacters(in: .whitespacesAndNewlines)
            rest.removeAll { old in
                let same = old.kind == .text
                    && old.text?.trimmingCharacters(in: .whitespacesAndNewlines) == key
                if same { dropped.append(old) }
                return same
            }
        }
        var out = [item] + rest
        if out.count > max(limit, 1) {
            dropped += out[max(limit, 1)...]
            out = Array(out.prefix(max(limit, 1)))
        }
        return (out, dropped)
    }
}

/// Clipboard contents Clipout must never store.
public enum PasteboardRules {
    /// Markers from nspasteboard.org that password managers and other apps
    /// put on secrets and temporary data.
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    public static let privateApps: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.apple.keychainaccess",
        "com.apple.Passwords",
    ]

    public static func shouldIgnore(types: [String], appBundleID: String?) -> Bool {
        if let app = appBundleID, privateApps.contains(app) { return true }
        return types.contains { privateTypes.contains($0) }
    }
}
